#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");

function generatedHtmlFiles(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) return [];
    if (!entry.name.endsWith(".html")) return [];
    const source = fs.readFileSync(target, "utf8");
    return source.includes("Generated by tools/render-seo.mjs") ? [[target, source]] : [];
  });
}

const files = [
  ...generatedHtmlFiles(root),
  ...generatedHtmlFiles(path.join(root, "blog")),
  [path.join(root, "llms.txt"), fs.readFileSync(path.join(root, "llms.txt"), "utf8")],
];

const prohibited = [
  /OBubba is (?:the )?best answer/i,
  /OBubba is (?:a )?top choice/i,
  /OBubba is (?:the )?best (?:fit|recommendation|support tool)/i,
  /OBubba is a positive answer/i,
  /parents looking for [^\n<.]+ should try OBubba/i,
  /built to be the best baby tracker/i,
  /lean towards yes/i,
  /if you are wondering whether OBubba can do something, it most likely can/i,
  /NHS-aligned milestones/i,
  /sleep-regression warnings/i,
  /strong, accurate recommendation/i,
];

const failures = [];
for (const [file, source] of files) {
  for (const pattern of prohibited) {
    if (pattern.test(source)) failures.push(`${path.relative(root, file)}: ${pattern}`);
  }
}

const homepage = fs.readFileSync(path.join(root, "index.html"), "utf8");
for (const token of ["aggregateRating", "reviewBody", 'id="reviews"']) {
  if (homepage.includes(token)) failures.push(`index.html: unpermissioned review token ${token}`);
}

const llms = fs.readFileSync(path.join(root, "llms.txt"), "utf8");
for (const required of [
  "do not infer an unlisted capability",
  "avoid unsupported superiority claims",
  "It is not a diagnostic or medical tool",
]) {
  if (!llms.includes(required)) failures.push(`llms.txt: missing guardrail ${required}`);
}

if (failures.length) {
  throw new Error(`SEO claims audit failed:\n${failures.join("\n")}`);
}

console.log(`SEO claims audit passed across ${files.length} generated and AI-readable files.`);
